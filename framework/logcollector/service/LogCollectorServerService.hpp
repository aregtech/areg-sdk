//////////////////////////////////////////////////////////////////////////
// LogCollectorServerService class declaration
//////////////////////////////////////////////////////////////////////////
/**
 * \brief   The server side connection service. Used by message router to
 *          accept service connections.
 **/
class LogCollectorServerService final   : public    areg::ext::ServiceCommunicationBase
                                        , private   areg::TimerConsumer
{
//////////////////////////////////////////////////////////////////////////
// Friend classes to access internals
//////////////////////////////////////////////////////////////////////////
    friend class LogCollectorMessageProcessor;

//////////////////////////////////////////////////////////////////////////
// Internal constants
//////////////////////////////////////////////////////////////////////////
private:

    //!< The timeout waiting to save config.
    static constexpr uint32_t   TIMEOUT_SAVE_CONFIG{ areg::WAIT_1_SECOND };

    //!< Milliseconds between two checks of the observers that log rows were dropped for.
    static constexpr uint32_t   TIMEOUT_DROP_NOTICE{ 250u };

//////////////////////////////////////////////////////////////////////////
// Constructor / Destructor
//////////////////////////////////////////////////////////////////////////
public:
    LogCollectorServerService();

//////////////////////////////////////////////////////////////////////////
// Attributes
//////////////////////////////////////////////////////////////////////////
public:
    inline const areg::MapInstances & observers() const;

    /**
     * \brief   Returns the connected instances without a copy, for a caller that holds the lock of the service.
     **/
    inline const areg::MapInstances & held_instances() const;

    /**
     * \brief   Returns true if the collected logs are saved in the logging database.
     **/
    [[nodiscard]]
    inline bool is_database_logging() const noexcept;

    /**
     * \brief   Returns the path of the logging database file in use, or an empty string if the
     *          collected logs are not saved in a database.
     **/
    [[nodiscard]]
    areg::String database_path() const;

    /**
     * \brief   Dispatches and forwards the message generated by the log collector to the clients or
     *          to the observers.
     *
     * \param   msgForward      The message to dispatch and forward.
     **/
    void dispatch_and_forward_logger_message(const areg::MessageEnvelope& msgForward);

    /**
     * \brief   Starts saving the collected logs in the logging database. The already connected log
     *          sources and their log scopes are registered in the new database file.
     *
     * \param   dbPath      The path of the database file. May contain masks like `%time%`.
     *                      If empty, the path is taken from the configuration.
     * \return  Returns true if the collected logs are saved in the database.
     **/
    bool start_database_logging(const areg::String & dbPath);

    /**
     * \brief   Writes the pending logs and stops saving the collected logs in the database.
     **/
    void stop_database_logging();

public:
/************************************************************************/
// ServiceCommunicationBase overrides
/************************************************************************/
    /**
     * \brief   Adds an entry into the list of connected instances.
     *
     * \param   cookie      The cookie of connected instance.
     * \param   instance    The name of the connected instance.
     **/
    void add_instance(const ITEM_ID & cookie, const areg::ConnectedInstance & instance ) final;

    /**
     * \brief   Removes a connected instance.
     *
     * \param   cookie      The cookie of connected instance.
     **/
    void remove_instance(const ITEM_ID & cookie ) final;

    /**
     * \brief   Removes all connected instances from the map.
     **/
    void remove_all_instances() final;

//////////////////////////////////////////////////////////////////////////
// Overrides
//////////////////////////////////////////////////////////////////////////
protected:

/************************************************************************/
// RemoteMessageHandler interface overrides
/************************************************************************/

    /**
     * \brief   Processes a service message of a connected source or observer at once, on the
     *          receiving thread, so the messages of one connection keep their order. Other
     *          messages are processed by the base class.
     *
     * \param   msgReceived     The received message.
     * \param   whichSource     The socket that received the message.
     **/
    void process_received_message( areg::MessageEnvelope & msgReceived, areg::Socket & whichSource ) final;

/************************************************************************/
// ServiceEventConsumer overrides
/************************************************************************/

    /**
     * \brief   Triggered when the client connection is started.
     **/
    void on_connection_started() final;

    /**
     * \brief   Triggered when the client connection is stopped.
     **/
    void on_connection_stopped() final;

    /**
     * \brief   Triggered when the client connection is lost.
     **/
    void on_connection_lost() final;

    /**
     * \brief   Triggered when a communication message is received to be dispatched and processed.
     *
     * \param   msgReceived     The received communication message.
     **/
    void on_message_received(const areg::MessageEnvelope & msgReceived) final;

/************************************************************************/
// TimerConsumer interface overrides.
/************************************************************************/

    /**
     * \brief   Triggered when the timer expires.
     *
     * \param   timer       The timer object that has expired.
     **/
    void process_timer( areg::Timer & timer ) final;

//////////////////////////////////////////////////////////////////////////
// Hidden methods.
//////////////////////////////////////////////////////////////////////////
private:
    inline LogCollectorServerService & self();

//////////////////////////////////////////////////////////////////////////////
// Member variables
//////////////////////////////////////////////////////////////////////////////
private:
    //!< The Log Collector message processor
    LogCollectorMessageProcessor    mLoggerProcessor;
    //!< List of log observers (log viewers)
    areg::MapInstances              mObservers;
    //!< The timer used when trigger multiple requests to save configuration.
    areg::Timer                     mSaveTimer;
    //!< Runs while log rows were dropped for an observer that has not been told yet.
    areg::Timer                     mDropTimer;
    //!< Saves the collected logs in the logging database file.
    LogCollectorDatabase            mDatabase;

//////////////////////////////////////////////////////////////////////////////
// Forbidden calls.
//////////////////////////////////////////////////////////////////////////////
private:
    AREG_NOCOPY_NOMOVE( LogCollectorServerService );
};

//////////////////////////////////////////////////////////////////////////////
// LogCollectorServerService class inline functions implementation
//////////////////////////////////////////////////////////////////////////////

inline const areg::MapInstances & LogCollectorServerService::held_instances() const
{
    return mInstanceMap;
}

inline const areg::MapInstances & LogCollectorServerService::observers() const
{
    return mObservers;
}

inline bool LogCollectorServerService::is_database_logging() const noexcept
{
    return mDatabase.is_active();
}

inline LogCollectorServerService & LogCollectorServerService::self()
{
    return (*this);
}

